/**
 * Escapes the 5 HTML special characters (`&`, `<`, `>`, `"`, `'`) into safe
 * HTML character entities so untrusted or punctuation-heavy strings (like quotes
 * inside `alt="..."` attributes or `<` inside prose) can never break HTML markup
 * or trigger Cross-Site Scripting (XSS).
 * Note: `&` MUST be replaced FIRST; otherwise replacing `<` -> `&lt;` first
 * would get double-escaped into `&amp;lt;`!
 * @param {string} str
 * @returns {string}
 */
function escapeHtml(str) {
  return String(str ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Safely serializes any JavaScript object/array for embedding directly inside an
 * HTML `<script type="application/json">` or `<script type="application/ld+json">` tag.
 *
 * Teaching Note — Why isn't `JSON.stringify(value)` enough inside `<script>`?
 *   HTML parsers scan `<script>` blocks looking for the literal character sequence
 *   `</script>` or `<!--` BEFORE JavaScript ever parses the JSON! If a dossier
 *   summary contained `</script>`, raw `JSON.stringify` would prematurely close
 *   the `<script>` tag and leak raw text onto the page. Replacing `<`, `>`, and `&`
 *   with standard JSON Unicode escapes (`\u003c`, `\u003e`, `\u0026`) keeps the
 *   JSON 100% identical when parsed by `JSON.parse()`, while making `</script>`
 *   impossible in the raw HTML stream.
 * @param {unknown} value
 * @returns {string}
 */
function safeJsonForScript(value) {
  return JSON.stringify(value)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026');
}

/**
 * Trims text cleanly at a natural word boundary within `maxLen` characters
 * (e.g., `<= 60` chars for `<title>` / `og:title` and `<= 155` chars for
 * `<meta name="description">` / `og:description`) and appends a single typographic
 * ellipsis (`…`) after stripping trailing punctuation.
 * @param {string} str
 * @param {number} maxLen
 * @returns {string}
 */
function clampMetaText(str, maxLen) {
  // Collapse newlines and repeated spaces into single spaces first
  const clean = String(str ?? '').replace(/\s+/g, ' ').trim();
  if (clean.length <= maxLen) return clean;
  // Reserve 1 character for the trailing `…` character
  const sliced = clean.slice(0, maxLen - 1);
  const lastSpace = sliced.lastIndexOf(' ');
  // Prefer breaking at the last space (as long as it's past 60% of `maxLen` so
  // we don't chop off half the string on a giant URL/word), and strip dangling commas/hyphens.
  return `${(lastSpace > maxLen * 0.6 ? sliced.slice(0, lastSpace) : sliced).replace(/[.,;:—–-]+$/, '')}…`;
}

/**
 * Generates a clean, deterministic URL-safe anchor slug from a Markdown heading
 * (e.g. `"4. The Poly Pass & Regional Transit"` -> `"4-the-poly-pass-regional-transit"`),
 * used for `<h2 id="sec-...">` deep-linking and the sticky "On This Page" rail.
 * @param {string} raw
 * @returns {string}
 */
function slugifyHeading(raw) {
  const stripped = String(raw ?? '')
    .replace(/<[^>]+>/g, '')        // Strip inline HTML tags (`<aac>`, `<br>`, etc.)
    .replace(/[`*_~[\]()]/g, '')    // Strip Markdown formatting delimiters
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')    // Collapse runs of non-alphanumeric chars into single hyphens
    .replace(/^-+|-+$/g, '');       // Trim leading/trailing hyphens
  return stripped || 'section';
}

/**
 * Writes a compiled HTML, CSS, JS, XML, or JSON file under `./dist/`,
 * automatically creating any nested parent folders (`{ recursive: true }`) first.
 * For example, `writeDistFile('books/rachel/index.html', html)` creates
 * `./dist/books/rachel/` and writes `index.html` as UTF-8 text.
 * @param {string} relPath
 * @param {string} content
 */
function writeDistFile(relPath, content) {
  const fullPath = path.join(distDir, relPath);
  fs.mkdirSync(path.dirname(fullPath), { recursive: true });
  fs.writeFileSync(fullPath, content, 'utf-8');
}

/**
 * Recursively copies static binary/vector assets from `public/` (`favicon.ico`,
 * `icons/*`) into `dist/`, skipping hidden dotfiles like `.DS_Store`.
 * @param {string} srcDir
 * @param {string} destDir
 */
function copyDirectoryRecursive(srcDir, destDir) {
  if (!fs.existsSync(srcDir)) return;
  fs.mkdirSync(destDir, { recursive: true });
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const srcPath = path.join(srcDir, entry.name);
    const destPath = path.join(destDir, entry.name);
    if (entry.isDirectory()) {
      copyDirectoryRecursive(srcPath, destPath);
    } else if (entry.isFile()) {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

