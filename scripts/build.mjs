// Optional zero-dependency local preview server (`npm run dev` / `npm run preview` -> `node scripts/build.mjs --serve`):
// Serves `./dist/` on `http://localhost:4328` (or `$PORT`) with clean directory `index.html` resolution,
// `404.html` fallback, accurate MIME `Content-Type` headers, and `Access-Control-Allow-Origin: *` CORS
// so local `books.raggiesoft.com` development can test `/api/v1/*.json` endpoints seamlessly!
if (process.argv.includes('--serve')) {
  const port = Number(process.env.PORT || 4328);
  const server = http.createServer((req, res) => {
    const urlPath = (req.url || '/').split('?')[0];
    let filePath = path.join(distDir, urlPath === '/' ? 'index.html' : urlPath);
    if (fs.existsSync(filePath) && fs.statSync(filePath).isDirectory()) {
      filePath = path.join(filePath, 'index.html');
    }
    if (!fs.existsSync(filePath)) {
      filePath = path.join(distDir, '404.html');
    }
    const ext = path.extname(filePath);
    const mime =
      ext === '.css'
        ? 'text/css; charset=utf-8'
        : ext === '.js'
          ? 'application/javascript; charset=utf-8'
          : ext === '.json'
            ? 'application/json; charset=utf-8'
            : ext === '.xml'
              ? 'application/xml; charset=utf-8'
              : ext === '.svg'
                ? 'image/svg+xml'
                : ext === '.png'
                  ? 'image/png'
                  : ext === '.ico'
                    ? 'image/x-icon'
                    : 'text/html; charset=utf-8';
    res.writeHead(200, {
      'Content-Type': mime,
      'Access-Control-Allow-Origin': '*'
    });
    res.end(fs.readFileSync(filePath));
  });
  server.listen(port, () => {
    console.log(`🚀 RaggieSoft Backstage preview server running at http://localhost:${port}`);
  });
}
