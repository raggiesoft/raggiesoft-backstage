/**
 * Loads all Backstage Markdown items from `/raggiesoft-narratives/backstage`
 * when building on the author's workstation, OR falls back transparently to
 * `src/data/backstage-snapshot.json` when building on the DigitalOcean NYC1
 * production Droplet (where private novel Markdown vaults are intentionally
 * never cloned!).
 */
function loadBackstageItems() {
  // Probe relative sibling paths where `raggiesoft-narratives/backstage` may live locally
  const candidates = [
    path.resolve(projectRoot, '../../../raggiesoft-novels/backstage'),
    path.resolve(projectRoot, '../../raggiesoft-novels/backstage'),
    path.resolve(projectRoot, '../raggiesoft-novels/backstage'),
    path.resolve(projectRoot, '../../../raggiesoft-narratives/backstage'),
    path.resolve(projectRoot, '../../raggiesoft-narratives/backstage'),
    path.resolve(projectRoot, '../raggiesoft-narratives/backstage')
  ];

  let narrativesDir = null;
  for (const c of candidates) {
    if (fs.existsSync(c) && fs.statSync(c).isDirectory()) {
      narrativesDir = c;
      break;
    }
  }

  if (narrativesDir) {
    // Workstation path: compile every `.md` file fresh from disk
    const relFiles = walkMarkdownFiles(narrativesDir);
    const items = relFiles.map((relFile) => {
      const raw = fs.readFileSync(path.join(narrativesDir, relFile), 'utf-8');
      const { frontmatter, body: rawBody } = parseFrontmatter(raw);
      // IMMUTABLE SEPTEMBER 11, 2001 ZERO-IMAGES FATAL GUARDRAIL (`backstage/scripts/build.mjs`):
      // Any Backstage dossier whose `date:` takes place on September 11, 2001 MUST NEVER
      // specify `image`, `images`, `ogImage`, `og_image`, inline `![...](...)`, or `<img>`.
      const rawDateStr = String(frontmatter.date || '').trim();
      if (/(?:\b2001-0?9-11\b|\b0?9[\/\-]11[\/\-]2001\b|\bSept(?:ember)?\.?\s+11(?:th)?,?\s+2001\b|\b11\s+Sept(?:ember)?\.?,?\s+2001\b)/i.test(rawDateStr)) {
        const hasFmImg = Boolean(
          (Array.isArray(frontmatter.image) ? frontmatter.image.length : String(frontmatter.image || '').trim()) ||
          (Array.isArray(frontmatter.images) ? frontmatter.images.length : String(frontmatter.images || '').trim()) ||
          String(frontmatter.ogImage || '').trim() ||
          String(frontmatter.og_image || '').trim()
        );
        const rawNoFences = String(rawBody || '').replace(/```[\s\S]*?```/g, '');
        const hasInlineImg = /!\[[^\]]*\]\([^)]+\)|<img\b/i.test(rawNoFences);
        if (hasFmImg || hasInlineImg) {
          console.error(
            `\n🛑 FATAL GUARDRAIL ERROR [IMMUTABLE SEPTEMBER 11, 2001 ZERO-IMAGES RULE]:\n` +
            `   Dossier: ${path.join(narrativesDir, relFile)}\n` +
            `   Date: ${rawDateStr}\n` +
            `   September 11, 2001 sections MUST NEVER contain rendered images. Aborting Backstage build.\n`
          );
          process.exit(1);
        }
      }
      const body = canonicalizeRaggieSoftUrlsInText(rawBody);

      // Map file paths to clean URL slugs:
      //   `books/rachel/index.md` -> slug `'books/rachel'` -> route `'/books/rachel'`
      //   `locations/cpi.md`      -> slug `'locations/cpi'` -> route `'/locations/cpi'`
      let slug = relFile.replace(/\.md$/, '');
      if (slug.endsWith('/index')) {
        slug = slug.slice(0, -'/index'.length);
      }
      const routePath = `/${slug}`;
      const toc = [];
      const html = renderMarkdownToHtml(body, toc);
      const image = frontmatter.image || '';
      const imageAlt = frontmatter.imageAlt || frontmatter.title || '';
      const ogImage = resolveOgImageForSlug(slug, frontmatter.ogImage || '');

      return {
        slug,
        routePath,
        canonicalUrl: `https://backstage.raggiesoft.com${routePath}`,
        apiUrl: `https://backstage.raggiesoft.com/api/v1/${slug}.json`,
        title: frontmatter.title || slug,
        subtitle: frontmatter.subtitle || '',
        category: frontmatter.category || 'Backstage Dossier',
        property: frontmatter.property || 'general',
        date: frontmatter.date || '',
        time: frontmatter.time || '',
        location: frontmatter.location || '',
        sender: frontmatter.sender || '',
        recipient: frontmatter.recipient || '',
        subject: frontmatter.subject || '',
        relatedBookUrl: canonicalizeRaggieSoftUrlsInText(frontmatter.relatedBookUrl || ''),
        relatedBookLabel: frontmatter.relatedBookLabel || 'Return to RaggieSoft Book Reader',
        image,
        imageAlt,
        ogImage,
        summary: frontmatter.summary || frontmatter.subtitle || frontmatter.title || '',
        toc,
        markdown: body,
        html
      };
    });

    // Sort items deterministically:
    //   1. Collection series hubs (`books/rachel`, `books/katie`, etc.) sort first (`0` vs `1`).
    //   2. Dated records sort chronologically (`YYYY-MM-DD` ISO strings sort chronologically via `localeCompare`!).
    //   3. Undated or same-day records break ties alphabetically by `slug`.
    items.sort((a, b) => {
      const aHub =
        a.slug === 'books/rachel' ||
        a.slug === 'books/katie' ||
        a.slug === 'books/quantum-directive-3-casey' ||
        a.slug === 'books/aubrie'
          ? 0
          : 1;
      const bHub =
        b.slug === 'books/rachel' ||
        b.slug === 'books/katie' ||
        b.slug === 'books/quantum-directive-3-casey' ||
        b.slug === 'books/aubrie'
          ? 0
          : 1;
      if (aHub !== bHub) return aHub - bHub;
      if (a.date && b.date && a.date !== b.date) return a.date.localeCompare(b.date);
      return a.slug.localeCompare(b.slug);
    });

    // Persist the compiled snapshot to `src/data/backstage-snapshot.json` for Droplet deployments
    fs.mkdirSync(path.dirname(snapshotPath), { recursive: true });
    fs.writeFileSync(snapshotPath, JSON.stringify(items, null, 2), 'utf-8');
    return items;
  }

  // Droplet fallback path: hydrate directly from the committed JSON snapshot
  if (fs.existsSync(snapshotPath)) {
    return JSON.parse(fs.readFileSync(snapshotPath, 'utf-8'));
  }

  throw new Error('Could not locate raggiesoft-narratives/backstage or backstage-snapshot.json');
}

