/**
 * Parses YAML frontmatter from the top of a Markdown file without requiring any
 * external npm YAML package.
 *
 * Example input Markdown file:
 *   ---
 *   title: "The Wingman Briefing"
 *   date: "1999-05-13"
 *   tags:
 *     - "Ashley Raybourn"
 *     - "Bonnie Reed"
 *   ---
 *   Narrative prose begins here...
 *
 * Returns `{ frontmatter: { title: "The Wingman Briefing", ... }, body: "Narrative prose..." }`.
 * @param {string} rawMd
 * @returns {{ frontmatter: Record<string, any>, body: string }}
 */
function parseFrontmatter(rawMd) {
  // Normalize Windows `\r\n` line endings to Unix `\n` so cross-platform edits parse identically
  const normalized = rawMd.replace(/\r\n/g, '\n');

  // Match an opening `---` fence at byte 0 (`^`), capture everything lazily (`[\s\S]*?`),
  // and stop at the closing `---` fence. If absent, treat the whole file as Markdown body.
  const match = normalized.match(/^---\s*\n([\s\S]*?)\n---\s*\n+/);
  if (!match) {
    return { frontmatter: {}, body: normalized };
  }
  const fmText = match[1];
  const body = normalized.slice(match[0].length);
  const frontmatter = {};

  // Tracks the active key when parsing multi-line YAML bullet lists (`key:\n  - item1\n  - item2`)
  let currentArrayKey = null;

  for (const line of fmText.split('\n')) {
    const trimmed = line.trim();
    // Skip blank lines and `#` YAML comments
    if (!trimmed || trimmed.startsWith('#')) continue;

    if (trimmed.startsWith('- ') && currentArrayKey) {
      // List item belonging to the most recently opened array key
      let val = trimmed.slice(2).trim();
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      frontmatter[currentArrayKey].push(val);
    } else {
      // Key-value pair (`key: value`) — slice at the FIRST colon only so values
      // containing colons (such as URLs `https://...` or timestamps `9:00 PM`) stay intact!
      const colonIdx = trimmed.indexOf(':');
      if (colonIdx !== -1) {
        const key = trimmed.slice(0, colonIdx).trim();
        let val = trimmed.slice(colonIdx + 1).trim();
        if (val === '') {
          // Empty value after `key:` starts a multi-line YAML array (`[]`)
          currentArrayKey = key;
          frontmatter[key] = [];
        } else {
          // Unwrap double-quoted strings via `JSON.parse` (decoding `\"` escapes cleanly)
          // or strip surrounding single quotes.
          if (val.startsWith('"') && val.endsWith('"')) {
            try {
              val = JSON.parse(val);
            } catch {
              val = val.slice(1, -1);
            }
          } else if (val.startsWith("'") && val.endsWith("'")) {
            val = val.slice(1, -1);
          }
          frontmatter[key] = val;
          currentArrayKey = null;
        }
      }
    }
  }
  return { frontmatter, body };
}

